relatable_patterns = [
    "same here",
    "me too",
    "i can relate",
    "i relate",
    "relatable",
    "literally me",
    "this is me",
    "this happened to me",
    "happened to me too",
    "happens to me",
    "i have experienced",
    "i experienced",
    "my experience",
    "going through this",
    "been through this",
    "i went through",
    "i've been through",
    "exactly me"
]

def detect_relatability(text):
    text = str(text).lower()

    for phrase in relatable_patterns:
        if phrase in text:
            return "Relatable"

    return "Neutral"

comments_df["relatability"] = comments_df["text"].apply(
    detect_relatability
)

